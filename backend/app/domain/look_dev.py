_VALID_LENS_CODES = {item["code"] for item in LENS_MATRIX}
_VALID_LIGHT_CODES = {item["code"] for item in LIGHTING_MATRIX}
_STYLE_CODES = [item["code"] for item in STYLE_CATALOG]

_SWATCH_ROLES = (
    "Primary Key",
    "Shadow/Depth",
    "Accent/Highlight",
    "Skin/Material Midtone",
    "Atmospheric Wash",
)


def _swatches(hexes: list[str], names: list[str]) -> list[dict[str, str]]:
    if len(hexes) != 5 or len(names) != 5:
        raise ValueError("Look-dev presets require exactly 5 palette swatches")
    return [
        {"role": role, "hex": hex_value, "name": name}
        for role, hex_value, name in zip(_SWATCH_ROLES, hexes, names)
    ]


def _preset(
    preset_id: str,
    label: str,
    mood_rationale: str,
    palette_hexes: list[str],
    palette_names: list[str],
    film_stock_or_medium: str,
    default_lens_code: str,
    default_light_code: str,
    aesthetic_directives: str,
    color_grade_emulation: str,
) -> dict[str, Any]:
    if default_lens_code not in _VALID_LENS_CODES:
        raise ValueError(f"Invalid lens code in look-dev preset: {default_lens_code}")
    if default_light_code not in _VALID_LIGHT_CODES:
        raise ValueError(f"Invalid light code in look-dev preset: {default_light_code}")
    return {
        "preset_id": preset_id,
        "label": label,
        "mood_rationale": mood_rationale,
        "palette_tokens": _swatches(palette_hexes, palette_names),
        "film_stock_or_medium": film_stock_or_medium,
        "default_lens_code": default_lens_code,
        "default_light_code": default_light_code,
        "aesthetic_directives": aesthetic_directives,
        "color_grade_emulation": color_grade_emulation,
    }


