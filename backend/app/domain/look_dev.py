def get_look_dev_presets(style_code: str) -> list[dict[str, Any]]:
    """Return the 3 curated presets for a canonical `#Style XX` code (deep copy)."""
    code = (style_code or "").strip()
    presets = LOOK_DEV_PRESETS.get(code)
    if presets is None:
        return []
    return copy.deepcopy(presets)


